/**
 * The feature tables of the catalog, rendered from one file per feature.
 *
 *   pnpm docs:catalog            # print the tables
 *   pnpm docs:catalog --write F  # write them to F
 *
 * A feature is `docs/reports/features/<section>/<slug>.md`: an `# Name` heading, a `Status:` line,
 * then at most one paragraph of notes. Each section folder's README holds its title and intro.
 * One file per feature means two feature PRs never edit the same lines.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
import { pathToFileURL } from 'url';

export const FEATURES_DIR = 'docs/reports/features';

/** Table order. A folder not named here is an error, so a new section is a decision. */
export const SECTIONS = ['staff', 'member', 'band', 'public', 'api'];

/**
 * @typedef {{ file: string, name: string, status: string, notes: string }} Feature
 * @typedef {{ dir: string, title: string, intro: string, features: Feature[] }} Section
 */

/**
 * @param {string} file
 * @param {string} text
 * @returns {{ feature: Feature | null, errors: string[] }}
 */
export function parseFeature(file, text) {
	const blocks = text
		.trim()
		.split(/\n\s*\n/)
		.map((b) => b.replace(/\s*\n\s*/g, ' ').trim());
	const [heading, statusLine, ...rest] = blocks;
	/** @type {string[]} */
	const errors = [];
	if (!heading?.startsWith('# ')) errors.push(`${file}: first line must be "# <feature name>"`);
	if (!statusLine?.startsWith('Status: '))
		errors.push(`${file}: second paragraph must be "Status: <status>"`);
	if (rest.length > 1)
		errors.push(`${file}: notes must be one paragraph; they render as one table cell`);
	if (errors.length) return { feature: null, errors };
	return {
		feature: {
			file,
			name: heading.slice(2).trim(),
			status: statusLine.slice('Status: '.length).trim(),
			notes: rest[0] ?? ''
		},
		errors
	};
}

/**
 * @param {string} [root]
 * @returns {{ sections: Section[], errors: string[] }}
 */
export function readCatalog(root = FEATURES_DIR) {
	/** @type {string[]} */
	const errors = [];
	/** @type {Section[]} */
	const sections = [];
	if (!existsSync(root)) return { sections, errors: [`${root} is missing`] };

	for (const entry of readdirSync(root, { withFileTypes: true })) {
		if (entry.isDirectory() && !SECTIONS.includes(entry.name))
			errors.push(`${root}/${entry.name} is not a section (${SECTIONS.join(', ')})`);
		else if (!entry.isDirectory() && entry.name !== 'README.md')
			errors.push(`${root}/${entry.name}: a feature goes in a section folder`);
	}

	for (const dir of SECTIONS) {
		const path = join(root, dir);
		if (!existsSync(path)) continue;
		const readme = join(path, 'README.md');
		const [titleLine = '', ...introLines] = existsSync(readme)
			? readFileSync(readme, 'utf-8').trim().split('\n')
			: [];
		if (!titleLine.startsWith('# ')) errors.push(`${readme} must start with "# <section title>"`);

		/** @type {Feature[]} */
		const features = [];
		const names = new Map();
		for (const name of readdirSync(path).sort()) {
			if (name === 'README.md') continue;
			const file = join(path, name);
			if (!name.endsWith('.md')) {
				errors.push(`${file}: features are .md files`);
				continue;
			}
			const parsed = parseFeature(file, readFileSync(file, 'utf-8'));
			errors.push(...parsed.errors);
			if (!parsed.feature) continue;
			const key = parsed.feature.name.toLowerCase();
			if (names.has(key))
				errors.push(`${file}: "${parsed.feature.name}" is also ${names.get(key)}`);
			names.set(key, file);
			features.push(parsed.feature);
		}
		features.sort((a, b) => a.name.localeCompare(b.name));
		sections.push({
			dir,
			title: titleLine.slice(2).trim(),
			intro: introLines.join('\n').trim(),
			features
		});
	}
	return { sections, errors };
}

const cell = (/** @type {string} */ s) => s.replace(/\|/g, '\\|');

/** @param {Section[]} sections */
export function renderCatalog(sections) {
	const out = [
		'<!-- Generated by `pnpm docs:catalog` from docs/reports/features/. Do not edit. -->',
		'',
		'# CorvMC features'
	];
	for (const s of sections) {
		out.push('', `## ${s.title}`, '');
		if (s.intro) out.push(s.intro, '');
		out.push('| Feature | Status | Notes |', '| --- | --- | --- |');
		for (const f of s.features)
			out.push(`| ${cell(f.name)} | ${cell(f.status)} | ${cell(f.notes)} |`);
	}
	return out.join('\n') + '\n';
}

function main() {
	const { sections, errors } = readCatalog();
	if (errors.length) {
		for (const e of errors) console.error(`✗ ${e}`);
		process.exit(1);
	}
	const text = renderCatalog(sections);
	const i = process.argv.indexOf('--write');
	if (i === -1) process.stdout.write(text);
	else writeFileSync(process.argv[i + 1], text);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
