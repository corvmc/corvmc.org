<script lang="ts">
	import QRCode from 'qrcode-svg';
	import { page } from '$app/state';
	import InfoCard from '$lib/components/ui/InfoCard.svelte';
	import Button from '$lib/components/ui/Button.svelte';
	import Alert from '$lib/components/ui/Alert.svelte';

	let {
		eventId,
		title,
		published,
		origin = page.url.origin
	}: {
		eventId: string;
		title: string;
		published: boolean;
		/** The site origin the code points at; the page's own unless a spec pins it. */
		origin?: string;
	} = $props();

	// Built by hand rather than with `resolve()`: the code must hold an absolute
	// URL, and a printed poster outlives any base path the app might gain.
	const href = $derived(`${origin}/events/${eventId}`);
	const slug = $derived(
		title
			.toLowerCase()
			.replace(/[^a-z0-9]+/g, '-')
			.replace(/^-|-$/g, '') || 'event'
	);

	// 'Q' error correction survives the smudges and creases of a printed poster.
	const svg = $derived(
		new QRCode({ content: href, width: 256, height: 256, padding: 2, ecl: 'Q', join: true }).svg()
	);
	const svgHref = $derived(`data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`);

	let copied = $state(false);

	async function copyLink() {
		await navigator.clipboard.writeText(href);
		copied = true;
		setTimeout(() => (copied = false), 2000);
	}

	/** Rasterise at print size: a 256px PNG blurs on anything larger than a flyer. */
	function downloadPng() {
		const size = 1200;
		const img = new Image();
		img.onload = () => {
			const canvas = document.createElement('canvas');
			canvas.width = size;
			canvas.height = size;
			const ctx = canvas.getContext('2d')!;
			ctx.imageSmoothingEnabled = false;
			ctx.drawImage(img, 0, 0, size, size);
			const a = document.createElement('a');
			a.href = canvas.toDataURL('image/png');
			a.download = `${slug}-qr.png`;
			a.click();
		};
		img.src = svgHref;
	}
</script>

<InfoCard title="QR code">
	{#if !published}
		<Alert type="warning" class="mb-3">
			This listing is not published yet, so the link shows nothing until it is.
		</Alert>
	{/if}

	<div class="flex flex-wrap items-start gap-4">
		<div
			data-testid="listing-qr"
			class="w-32 shrink-0 rounded bg-white p-2 [&_svg]:h-auto [&_svg]:w-full"
		>
			<!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by qrcode-svg from our own URL -->
			{@html svg}
		</div>
		<div class="min-w-0 space-y-2">
			<p class="text-sm break-all">{href}</p>
			<div class="flex flex-wrap gap-2">
				<Button size="sm" onclick={copyLink}>{copied ? 'Copied' : 'Copy link'}</Button>
				<Button size="sm" href={svgHref} download="{slug}-qr.svg">Download SVG</Button>
				<Button size="sm" onclick={downloadPng}>Download PNG</Button>
			</div>
			<p class="text-muted text-xs">SVG scales to any print size; PNG is 1200px.</p>
		</div>
	</div>
</InfoCard>
