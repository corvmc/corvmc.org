<script lang="ts">
	import QRCode from 'qrcode-svg';
	import { page } from '$app/state';
	import { resolve } from '$app/paths';
	import Button from '$lib/components/ui/Button.svelte';

	/**
	 * The sign for the back door (#2120): a QR code to `/door`. The URL holds no
	 * secret, so the poster never needs reprinting. Built by hand rather than
	 * with `resolve()`, since a printed code must hold an absolute URL.
	 */
	const href = $derived(`${page.url.origin}/door`);
	// 'Q' error correction survives the weather on an outside door.
	const svg = $derived(
		new QRCode({ content: href, width: 512, height: 512, padding: 2, ecl: 'Q', join: true }).svg()
	);
	const svgHref = $derived(`data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`);
</script>

<svelte:head>
	<title>Back door poster</title>
	<style>
		@media print {
			.no-print {
				display: none !important;
			}
		}
	</style>
</svelte:head>

<!-- Below the app topbar, as on the input list: this renders inside the staff panel. -->
<div class="no-print fixed top-16 right-4 z-50 flex gap-2">
	<Button variant="primary" size="sm" onclick={() => window.print()}>Print</Button>
	<Button size="sm" variant="ghost" href={svgHref} download="back-door-qr.svg">Download SVG</Button>
	<Button href={resolve('/staff/keys')} variant="ghost" size="sm">&larr; Key Holders</Button>
</div>

<div class="poster">
	<h1>Check in here</h1>
	<div class="qr" data-testid="door-qr">
		<!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by qrcode-svg from our own URL -->
		{@html svg}
	</div>
	<p class="lead">Scan with your phone camera to open the door for your booking.</p>
	<p class="small">{href}</p>
	<p class="small">No signal here? Open the page before you arrive.</p>
</div>

